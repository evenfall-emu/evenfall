import {
  definePreparedGame,
  type BridgeSample,
  type BuildProfile,
  type DecodeResult,
  type GameDefinition,
  type GameIdentity,
  type MemoryLayout,
  type MemoryReader,
  type MemoryRef,
} from "./contract.js";
import { array, ref, type MemoryArrayRef } from "./memory.js";

/**
 * Finds a source in a ROM image. Tools run locators to write and check build
 * manifests; the player only reads the addresses a manifest records.
 */
export interface Locator {
  readonly id: string;
  /**
   * The locator finds a neighbouring value and assumes the layout next to it
   * (a field at a fixed offset from a global), rather than finding the value.
   */
  readonly inferred?: boolean;
  /** Candidate guest addresses, best first. `rom` is the raw cartridge image. */
  find(rom: Uint8Array): readonly number[];
}

/** One value in work RAM at the address a manifest gives. */
export interface RamSource<T> {
  readonly kind: "ram";
  readonly layout: MemoryLayout<T>;
  readonly locate?: readonly Locator[];
}
/** A fixed-length array in work RAM; views read slots with `at()`. */
export interface RamArraySource<T> {
  readonly kind: "ramArray";
  readonly layout: MemoryLayout<T>;
  readonly length: number;
  readonly locate?: readonly Locator[];
}
export type Source = RamSource<any> | RamArraySource<any>;
export type Sources = Readonly<Record<string, Source>>;

export function ram<T>(
  layout: MemoryLayout<T>,
  options: { readonly locate?: readonly Locator[] } = {},
): RamSource<T> {
  return Object.freeze({ kind: "ram", layout, ...options });
}
export function ramArray<T>(
  layout: MemoryLayout<T>,
  length: number,
  options: { readonly locate?: readonly Locator[] } = {},
): RamArraySource<T> {
  return Object.freeze({ kind: "ramArray", layout, length, ...options });
}

/**
 * Adds locators to sources, typically a module generated by
 * `node tools/bridge.mjs signatures`. Unknown source names are type errors.
 */
export function locateWith<S extends Sources>(
  sources: S,
  locators: { readonly [K in keyof S]?: readonly Locator[] },
): S {
  return Object.fromEntries(
    Object.entries(sources).map(([name, source]) => {
      const locate = locators[name as keyof S];
      return [name, locate ? Object.freeze({ ...source, locate }) : source];
    }),
  ) as S;
}

/** The references views receive: each source at its build's address. */
export type SymbolsOf<S extends Sources> = {
  readonly [K in keyof S]: S[K] extends RamArraySource<infer T>
    ? MemoryArrayRef<T>
    : S[K] extends RamSource<infer T>
      ? MemoryRef<T>
      : never;
};

/** What a view reads: one captured sample and the ROM resources of its build. */
export interface ViewContext<S extends Sources, Resources> {
  readonly memory: MemoryReader;
  readonly symbols: SymbolsOf<S>;
  readonly sample: BridgeSample;
  readonly resources: Resources;
}
/** Pure and synchronous; may return functions (a search) as well as data. */
export type View<S extends Sources, Resources, T> = (
  context: ViewContext<S, Resources>,
) => DecodeResult<T>;

type OptionalKeys<T> = {
  [K in keyof T]-?: {} extends Pick<T, K> ? K : never;
}[keyof T];
type RequiredKeys<T> = Exclude<keyof T, OptionalKeys<T>>;
/** One view per field of `Views`; optional fields may be left out. */
export type ViewsOf<Views, S extends Sources, Resources> = {
  readonly [K in RequiredKeys<Views>]: View<S, Resources, Views[K]>;
} & {
  readonly [K in OptionalKeys<Views>]?: View<
    S,
    Resources,
    Exclude<Views[K], undefined>
  >;
};

/** Built once per ROM from the manifest's `rom` data: catalogs, artwork, indexes. */
export interface RomContext<Rom> {
  readonly rom: MemoryReader;
  readonly romHash: string;
  readonly config: Rom;
}

/**
 * A game family or one game: what it reads (sources), what it prepares from
 * the ROM (resources) and what it gives its overlay (views). A game is usually
 * a family spread with some sources, resources or views replaced.
 */
export interface Family<Views, S extends Sources, Resources, Rom> {
  readonly id: string;
  readonly sources: S;
  readonly resources: (context: RomContext<Rom>) => Resources;
  readonly views: ViewsOf<Views, S, Resources>;
  /**
   * Named checks of a build's ROM data, run by tools against a user ROM: each
   * throws when the resources do not decode as the family expects.
   */
  readonly probes?: Readonly<
    Record<string, (resources: Resources, romHash: string) => void>
  >;
  /** Locators for addresses in the manifest's ROM data, keyed by path. */
  readonly romLocators?: RomLocators<Rom>;
  /** How to recognize this family's builds cheaply (see `detectFamily`). */
  readonly detect?: FamilyDetector;
  /**
   * SHA-1 of the reviewed build the locators were generated from (exported by
   * a generated locator module). Its manifest is the template for located
   * builds: the values locators cannot find come from it.
   */
  readonly locatedFrom?: string;
}

export interface FamilyDetector {
  /** Cartridge header game codes (at 0xac) the family's builds keep, e.g. `"BPEE"`. */
  readonly gameCodes?: readonly string[];
  /** Locators that must find something; by default a few of the sources' own. */
  readonly markers?: readonly Locator[];
}

/**
 * Dotted paths to the numbers in a family's ROM data (`"catalog.species"`),
 * the values a ROM locator can find. Index signatures and arrays are skipped.
 */
export type RomPaths<
  T,
  Prefix extends string = "",
  Depth extends 0[] = [],
> = Depth["length"] extends 4
  ? never
  : T extends number
    ? Prefix
    : T extends readonly unknown[]
      ? never
      : T extends object
        ? {
            [K in keyof T & string]-?: string extends K
              ? never
              : RomPaths<
                  NonNullable<T[K]>,
                  Prefix extends "" ? K : `${Prefix}.${K}`,
                  [...Depth, 0]
                >;
          }[keyof T & string]
        : never;
export type RomLocators<Rom> = {
  readonly [Path in RomPaths<Rom>]?: readonly Locator[];
};

/**
 * Checks a family against the views its overlay needs and the ROM data its
 * manifests carry, and infers everything else from the object:
 * `defineFamily<MyViews, MyRom>()({ id, sources, resources, views })`.
 */
export function defineFamily<Views, Rom = undefined>() {
  return <S extends Sources, Resources>(family: {
    readonly id: string;
    readonly sources: S;
    readonly resources: (context: RomContext<Rom>) => Resources;
    // Sources and resources are inferred from their own fields, never from views.
    readonly views: ViewsOf<Views, NoInfer<S>, NoInfer<Resources>>;
    readonly probes?: Readonly<
      Record<string, (resources: NoInfer<Resources>, romHash: string) => void>
    >;
    readonly romLocators?: RomLocators<Rom>;
    readonly detect?: FamilyDetector;
    readonly locatedFrom?: string;
  }): Family<Views, S, Resources, Rom> => family;
}

/**
 * One exact build: its identity, where each source lives, and the ROM data
 * its resources read. Plain JSON, so tools can write and check it.
 */
export interface Manifest<S extends Sources, Rom> {
  readonly family: string;
  readonly romHash: string;
  readonly source: BuildProfile<{}>["source"];
  readonly addresses: { readonly [K in keyof S]: number };
  readonly rom: Rom;
  readonly provenance: {
    /** Reviewed by hand, relocated from a parent build, or found by locators. */
    readonly method: "reviewed" | "relocated" | "located";
    /** SHA-1 of the build this one was relocated from. */
    readonly parent?: string;
  };
}
export type ManifestOf<F> =
  F extends Family<any, infer S, any, infer Rom> ? Manifest<S, Rom> : never;

// Optional views stay optional: a family may leave them out, and then the
// game has no bridge for them.
type BridgesOf<Views, S extends Sources, Resources> = {
  readonly [K in keyof ViewsOf<Views, S, Resources> as K & string]: {
    readonly id: K & string;
    readonly decode: NonNullable<ViewsOf<Views, S, Resources>[K]>;
  };
};

/** What `createGame` keeps per game, so builds can be added at runtime. */
interface GameBuilds {
  readonly family: Family<any, any, any, any>;
  readonly manifests: Map<string, Manifest<any, any>>;
  readonly profiles: BuildProfile<any>[];
  readonly reviewed: ReadonlySet<string>;
  /** Present when the family has locators and its `locatedFrom` build is reviewed. */
  readonly template?: Manifest<any, any>;
  readonly version: string;
}
// A registry symbol rather than a module-level map, so a game made by one copy
// of the SDK is still recognized by another (duplicate installs, tool bundles).
const BUILDS = Symbol.for("@evenfall/gba/bridge/game-builds");

/**
 * The player-facing game: a family plus the builds it recognizes. The
 * `manifests` are reviewed builds; a family with locators can recognize
 * further builds at runtime (`locateGame`, then `registerBuild`).
 */
export function createGame<Views, S extends Sources, Resources, Rom>(
  family: Family<Views, S, Resources, Rom>,
  manifests: readonly [Manifest<S, Rom>, ...Manifest<S, Rom>[]],
): GameDefinition<
  string,
  SymbolsOf<S>,
  BridgesOf<Views, S, Resources>,
  Resources
> {
  const builds = new Map<string, Manifest<S, Rom>>();
  for (const manifest of manifests) {
    checkManifest(family, manifest);
    builds.set(manifest.romHash, manifest);
  }
  const profiles = manifests.map((manifest) => profileOf(family, manifest));
  const bridges = Object.fromEntries(
    Object.entries(family.views as Record<string, unknown>)
      .filter(([, view]) => view !== undefined)
      .map(([id, view]) => [id, { id, decode: view }]),
  ) as unknown as BridgesOf<Views, S, Resources>;
  const hasLocators =
    Object.values(family.sources).some((source) => source.locate?.length) ||
    Object.keys(family.romLocators ?? {}).length > 0;
  const template = family.locatedFrom
    ? builds.get(family.locatedFrom)
    : undefined;
  if (family.locatedFrom && !template)
    throw new Error(
      `${family.id} locators come from ${family.locatedFrom}, which is not one of its reviewed builds`,
    );
  const game = definePreparedGame(({ rom, romHash }) => {
    const manifest = builds.get(romHash);
    if (!manifest) throw new Error(`No ${family.id} manifest for ${romHash}`);
    return family.resources({ rom, romHash, config: manifest.rom });
    // The mapped view types are checked at the family; the generic runtime
    // shape is the same GameDefinition every game uses.
  })({ id: family.id, profiles, bridges } as never) as GameDefinition<
    string,
    SymbolsOf<S>,
    BridgesOf<Views, S, Resources>,
    Resources
  >;
  const record: GameBuilds = {
    family,
    manifests: builds,
    // The game shares this array, so registered builds are seen by
    // `resolveGame`, `decodeGame` and the host without copying the game.
    profiles,
    reviewed: new Set(builds.keys()),
    ...(hasLocators && template ? { template } : {}),
    version: locatorVersion(family, template),
  };
  Object.defineProperty(game, BUILDS, { value: record });
  return game;
}

function profileOf<S extends Sources, Rom>(
  family: Family<any, S, any, Rom>,
  manifest: Manifest<S, Rom>,
): BuildProfile<SymbolsOf<S>> {
  return {
    romHash: manifest.romHash,
    source: manifest.source,
    symbols: resolveSources(family.sources, manifest.addresses),
  };
}

/** A digest of what locating depends on: the locators and the template build. */
function locatorVersion(
  family: Family<any, any, any, any>,
  template: Manifest<any, any> | undefined,
): string {
  const parts = [
    family.id,
    template?.romHash ?? "",
    ...Object.entries(family.sources as Sources).flatMap(([name, source]) =>
      (source.locate ?? []).map((locator) => `${name}=${locator.id}`),
    ),
    ...Object.entries(
      (family.romLocators ?? {}) as Record<string, readonly Locator[]>,
    ).flatMap(([path, locators]) => locators.map((l) => `${path}=${l.id}`)),
  ];
  let h1 = 0x811c9dc5,
    h2 = 0x9e3779b9;
  for (const char of parts.join("\n")) {
    const code = char.charCodeAt(0);
    h1 = Math.imul(h1 ^ code, 16777619);
    h2 = Math.imul(h2 ^ code, 2246822519) ^ (h2 >>> 15);
  }
  return `${(h1 >>> 0).toString(16).padStart(8, "0")}${(h2 >>> 0).toString(16).padStart(8, "0")}`;
}

// Games made with `defineGame` have no record: they know only reviewed builds.
const recordOf = (game: object): GameBuilds | undefined =>
  (game as { [BUILDS]?: GameBuilds })[BUILDS];

function buildsOf(game: object): GameBuilds {
  const builds = recordOf(game);
  if (!builds) throw new Error("Not a game created with createGame");
  return builds;
}

/**
 * Whether `game` can recognize unreviewed builds: its family, the reviewed
 * manifest its locators come from, and a version that changes whenever the
 * locators or that template change (for caching located builds). Null for a
 * game without locators, or one not made with `createGame`.
 */
export function locatable(game: object): {
  readonly family: Family<any, any, any, any>;
  readonly template: Manifest<any, any>;
  readonly version: string;
} | null {
  const builds = recordOf(game);
  return builds?.template
    ? {
        family: builds.family,
        template: builds.template,
        version: builds.version,
      }
    : null;
}

/**
 * Adds a located (or cached) build to `game`, so the host, the hooks and
 * `decodeGame` treat it like a reviewed one. A build it already has is kept.
 */
export function registerBuild(
  game: object,
  manifest: Manifest<any, any>,
): void {
  const builds = buildsOf(game);
  if (builds.manifests.has(manifest.romHash)) return;
  checkManifest(builds.family, manifest);
  builds.manifests.set(manifest.romHash, manifest);
  builds.profiles.push(profileOf(builds.family, manifest));
}

/** Removes a build added with `registerBuild`; reviewed builds stay. */
export function unregisterBuild(game: object, romHash: string): void {
  const builds = recordOf(game);
  if (!builds || builds.reviewed.has(romHash)) return;
  builds.manifests.delete(romHash);
  const index = builds.profiles.findIndex((p) => p.romHash === romHash);
  if (index >= 0) builds.profiles.splice(index, 1);
}

/** How `game` knows the build `romHash`: reviewed, located at runtime, or not at all. */
export function buildProvenance(
  game: GameIdentity,
  romHash: string,
): "reviewed" | "located" | null {
  const builds = recordOf(game);
  if (!builds)
    return game.profiles.some((p) => p.romHash === romHash) ? "reviewed" : null;
  if (builds.reviewed.has(romHash)) return "reviewed";
  return builds.manifests.has(romHash) ? "located" : null;
}

/** Runtime check for manifests that arrive as JSON rather than typed code. */
export function checkManifest<S extends Sources, Rom>(
  family: Family<any, S, any, Rom>,
  manifest: Manifest<S, Rom>,
): void {
  const where = `${family.id} manifest ${manifest.romHash}`;
  if (manifest.family !== family.id)
    throw new Error(`${where} targets ${manifest.family}`);
  if (!/^[0-9a-f]{40}$/.test(manifest.romHash))
    throw new Error(`${where}: romHash must be a lowercase SHA-1`);
  const addresses = manifest.addresses as Record<string, unknown>;
  for (const name of Object.keys(family.sources))
    if (!Number.isInteger(addresses[name]) || (addresses[name] as number) < 0)
      throw new Error(`${where}: missing address for ${name}`);
  for (const name of Object.keys(addresses))
    if (!(name in family.sources))
      throw new Error(`${where}: unknown source ${name}`);
  // Generated locator modules can go stale when the ROM data type changes.
  for (const path of Object.keys(family.romLocators ?? {})) {
    const value = path
      .split(".")
      .reduce<unknown>(
        (node, key) =>
          node && typeof node === "object"
            ? (node as Record<string, unknown>)[key]
            : undefined,
        manifest.rom,
      );
    if (typeof value !== "number")
      throw new Error(`${where}: ROM locator path ${path} names no number`);
  }
}

function resolveSources<S extends Sources>(
  sources: S,
  addresses: { readonly [K in keyof S]: number },
): SymbolsOf<S> {
  return Object.freeze(
    Object.fromEntries(
      Object.entries(sources).map(([name, source]) => {
        const address = addresses[name as keyof S];
        return [
          name,
          source.kind === "ramArray"
            ? array(address, source.layout, source.length)
            : ref(address, source.layout),
        ];
      }),
    ),
  ) as SymbolsOf<S>;
}
