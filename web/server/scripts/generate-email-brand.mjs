// Regenerate the email's inline PNG from the checked-in logo and wordmark.
// Uses the workspace's Playwright dependency; no assets from artifacts/.
import { readFile, writeFile } from "node:fs/promises";
import { chromium } from "@playwright/test";

const root = new URL("../../../", import.meta.url);
const logo = await readFile(
  new URL("web/player/src/assets/brand/evenfall-logo.svg", root),
  "base64",
);
const browser = await chromium.launch({
  executablePath: process.env.CHROMIUM_EXECUTABLE_PATH,
});
try {
  const page = await browser.newPage({ deviceScaleFactor: 2 });
  await page.setContent(`<!doctype html><style>
    body { margin: 0; }
    #logo { display: block; width: 260px; height: 64px; background: #101c2a; }
  </style>
  <img id="logo" src="data:image/svg+xml;base64,${logo}">`);
  await page.locator("#logo").evaluate((image) => image.decode());
  const png = (await page.locator("#logo").screenshot()).toString("base64");
  await writeFile(
    new URL("web/server/src/email-brand.ts", root),
    "// Generated by web/server/scripts/generate-email-brand.mjs from web/player/src/assets/brand/evenfall-logo.svg.\n" +
      `export const emailLogo = ${JSON.stringify(png)};\n`,
  );
} finally {
  await browser.close();
}
